#!/usr/bin/env node
// Build one weekday tier of the daily puzzle and append it to daily.js.
//   node tools/build-daily.js <day> [--seconds 600] [--seed 7] [--out daily.js]
// Runs append, so a long weekend search can run in several passes with fresh seeds.
// Every kept board passes screen(): the tier's par range and rule count, the campaign's trap-rate and line-count
// range, a small hint search, no near-copy of a campaign level or another daily board, and every checked rule
// changes par. The tool refuses to run once daily.js is frozen: a shipped tier never changes.
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const E = require('../engine.js');
const {addDetail, matters, hintCheap} = require('./metrics.js');
const {makeRng} = require('./board-builder.js');
const {candidates} = require('./presets.js');
const {search} = require('./combine.js');
const T = require('./daily-tiers.js');

const LEVEL_FIELDS = ['board', 'homes', 'cost', 'fragile', 'links', 'locked', 'clipboard', 'nudges', 'consolidate', 'offset'];
const HEADER = '// Generated by tools/build-daily.js. Do not edit by hand.';

function readDaily(file) {
  const empty = Object.fromEntries(T.DAYS.map(day => [day, []]));
  if (!fs.existsSync(file)) return {tiers: empty, commands: [], frozen: false};
  const source = fs.readFileSync(file, 'utf8');
  const loaded = vm.runInNewContext(source + '\n;({tiers: typeof dailyTiers === "undefined" ? {} : dailyTiers, frozen: typeof dailyFrozen === "undefined" ? false : dailyFrozen})');
  const commands = source.split('\n').filter(line => line.startsWith('// $ ')).map(line => line.slice(5));
  // JSON copy: objects made in the vm context fail deepStrictEqual against this realm's objects.
  return {tiers: {...empty, ...JSON.parse(JSON.stringify(loaded.tiers))}, commands, frozen: Boolean(loaded.frozen)};
}

function writeDaily(file, {tiers, commands, frozen}) {
  const lines = [HEADER, ...commands.map(command => '// $ ' + command), `const dailyFrozen = ${Boolean(frozen)};`, 'const dailyTiers = {'];
  for (const day of T.DAYS) {
    lines.push(`  ${day}: [`);
    for (const board of tiers[day] ?? []) lines.push('    ' + JSON.stringify(board) + ',');
    lines.push('  ],');
  }
  lines.push('};', "if (typeof module !== 'undefined') module.exports = {dailyTiers, dailyFrozen};", '');
  fs.writeFileSync(file, lines.join('\n'));
}

const percentile = (values, p) => {
  const sorted = [...values].sort((a, b) => a - b);
  return sorted[Math.min(sorted.length - 1, Math.floor(p * sorted.length))];
};

// The 10th-percentile trap rate and the 90th-percentile line count of the non-intro campaign levels.
function qualityBounds(campaign) {
  const metrics = campaign.filter(level => !level.intro).map(level => addDetail(level, {par: E.solve(level).cost}, 3e5));
  return {minTrap: percentile(metrics.map(m => m.trapRate), 0.1), maxPaths: percentile(metrics.map(m => m.paths), 0.9)};
}

// qualityBounds, cached in `file` under a key built from the campaign boards. A changed campaign recomputes.
function cachedBounds(campaign, file = path.join(__dirname, 'daily-bounds.json')) {
  const key = JSON.stringify(campaign.filter(level => !level.intro).map(level => [level.id, level.board, level.homes, level.cost, level.fragile, level.links]));
  try {
    const saved = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (saved.key === key) return saved.bounds;
  } catch {}
  const bounds = qualityBounds(campaign);
  fs.writeFileSync(file, JSON.stringify({key, bounds}) + '\n');
  return bounds;
}

// The first reason to drop a candidate, or null to keep it. Cheap checks first.
// The candidate carries its par and metrics (trapRate, paths) and its `checked` rules.
function screen(candidate, {day, kept, campaign, bounds}) {
  const count = T.countProblem(day, candidate.checked);
  if (count) return count;
  const [low, high] = T.parRange(day, candidate);
  if (candidate.par < low || candidate.par > high) return 'par out of range';
  if (candidate.trapRate < bounds.minTrap) return 'trap rate too low';
  if (candidate.paths > bounds.maxPaths) return 'too many lines';
  const outside = T.outsideTier(day, T.boardRules(candidate));
  if (outside.length) return `uses ${outside.join(', ')}, outside ${day}`;
  if (T.tooSimilar(candidate, [...kept, ...campaign.filter(level => !level.intro)])) return 'similar';
  if (!hintCheap(candidate, T.HINT_LIMIT)) return 'hint too slow';
  try {
    if (!candidate.checked.every(rule => matters(candidate, rule, candidate.par))) return 'checked rule does not change par';
  } catch {
    return 'checked rule could not be checked';
  }
  return null;
}

// The board as daily.js stores it: id, labels, and only the level fields it uses.
function stored(candidate, id) {
  const board = {id, mechanic: candidate.checked[0], par: candidate.par, rules: T.boardRules(candidate), checked: candidate.checked};
  for (const field of LEVEL_FIELDS) {
    const value = candidate[field];
    if (value === undefined || value === false || value === 0 || (Array.isArray(value) && !value.length)) continue;
    if (field === 'homes' && !Object.keys(value).length) continue;
    board[field] = value;
  }
  return board;
}

// Candidates for one tier, one batch at a time, until `stop`.
function* batches(day, rng, stop) {
  const tier = T.TIERS[day];
  const ORDER = require('../levels.js').mechanics.map(m => m.id);
  for (let round = 0; Date.now() < stop; round++) {
    if (tier.sources) {
      const source = tier.sources[round % tier.sources.length];
      yield candidates(source.preset, {rng, tries: 150, count: 40, par: source.par ?? tier.par}).map(level => ({...level, checked: source.checked}));
    } else {
      const rules = rng.shuffle([...T.ADVANCED]).slice(0, tier.combine).sort((a, b) => ORDER.indexOf(a) - ORDER.indexOf(b));
      const length = rng.between(12, 18);
      const found = search(rules, {
        sizes: [3, 2, 2], free: 3, length, active: length, minPar: tier.par[0], par: null,
        seed: rng.between(1, 1e9), tries: 4000, count: 10, seconds: Math.max(1, Math.min(120, (stop - Date.now()) / 1000)), hintLimit: T.HINT_LIMIT,
      }, [], {});
      yield found.map(level => ({...level, checked: rules}));
    }
  }
}

// Hold a lock file while `fn` runs, so parallel runs never overwrite each other's tiers.
function withLock(file, fn) {
  const lock = file + '.lock';
  const started = Date.now();
  for (;;) {
    try {
      fs.closeSync(fs.openSync(lock, 'wx'));
      break;
    } catch (error) {
      if (error.code !== 'EEXIST' || Date.now() - started > 60000) throw error;
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
    }
  }
  try {
    return fn();
  } finally {
    fs.unlinkSync(lock);
  }
}

// Append stored boards to `day` in the latest `file`, renumbering their ids. Boards too like a board that another
// run added meanwhile are dropped. Returns how many were added.
function mergeInto(file, day, boards, command) {
  return withLock(file, () => {
    const data = readDaily(file);
    const others = T.DAYS.flatMap(d => data.tiers[d]);
    const tier = data.tiers[day];
    const prefix = day.slice(0, 3);
    let next = Math.max(0, ...tier.map(board => Number(board.id.split('-')[1]))) + 1;
    const added = [];
    for (const board of boards) {
      if (tier.length + added.length >= T.TARGET_TIER) break;
      if (T.tooSimilar(board, [...others, ...added])) continue;
      added.push({...board, id: `${prefix}-${next++}`});
    }
    data.tiers[day] = [...tier, ...added];
    if (added.length && !data.commands.includes(command)) data.commands.push(command);
    writeDaily(file, data);
    return added.length;
  });
}

function build(day, {seconds, seed, out, command}) {
  const data = readDaily(out);
  if (data.frozen) {
    console.error(`${path.basename(out)} is frozen: shipped tiers never change. Make a new pool version instead.`);
    process.exit(1);
  }
  const campaign = require('../levels.js').levels;
  const bounds = cachedBounds(campaign);
  const rng = makeRng(seed);
  const stop = Date.now() + seconds * 1000;
  let kept = T.DAYS.flatMap(d => data.tiers[d]);
  let added = 0;
  let total = data.tiers[day].length;
  const drops = {};
  // Merge after every batch, so a long run that is stopped keeps what it found.
  for (const batch of batches(day, rng, stop)) {
    const accepted = [];
    for (const candidate of batch) {
      const reason = screen(candidate, {day, kept: [...kept, ...accepted], campaign, bounds});
      if (reason) {
        drops[reason] = (drops[reason] ?? 0) + 1;
        continue;
      }
      accepted.push(candidate);
    }
    if (accepted.length) {
      const ranked = accepted.sort((a, b) => b.quality - a.quality).map((candidate, i) => stored(candidate, `new-${i}`));
      added += mergeInto(out, day, ranked, command);
      const latest = readDaily(out);
      kept = T.DAYS.flatMap(d => latest.tiers[d]);
      total = latest.tiers[day].length;
    }
    if (total >= T.TARGET_TIER) break;
  }
  console.log(`${day}: ${total} boards (min ${T.MIN_TIER}), ${added} added; bounds ${JSON.stringify(bounds)}; dropped ${JSON.stringify(drops)}`);
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const day = args[0];
  if (!T.DAYS.includes(day)) {
    console.error(`usage: node tools/build-daily.js <${T.DAYS.join('|')}> [--seconds 600] [--seed 7] [--out daily.js]`);
    process.exit(1);
  }
  const flag = (name, fallback) => {
    const at = args.indexOf('--' + name);
    return at < 0 ? fallback : args[at + 1];
  };
  const out = path.resolve(flag('out', path.join(__dirname, '..', 'daily.js')));
  build(day, {seconds: Number(flag('seconds', 600)), seed: Number(flag('seed', 7)), out, command: 'node tools/build-daily.js ' + args.filter((a, i) => a !== '--out' && args[i - 1] !== '--out').join(' ')});
}

module.exports = {readDaily, writeDaily, qualityBounds, cachedBounds, screen, stored, mergeInto};
